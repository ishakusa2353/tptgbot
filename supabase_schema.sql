-- ==============================================================================
-- SUPABASE SCHEMA FOR "ishak_licenses" TABLE
-- Project: Ishak AI Trading Bot License System
-- Integrated with Ishak Telegram Reseller Management Bot
-- ==============================================================================

CREATE TABLE IF NOT EXISTS ishak_licenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_key VARCHAR(100) UNIQUE NOT NULL,
    reseller_id VARCHAR(50) NOT NULL, -- Reseller Code or Telegram ID (e.g. RSL-82748)
    reseller_name VARCHAR(150),
    reseller_telegram_id BIGINT,
    package_name VARCHAR(100),
    duration_days INTEGER NOT NULL CHECK (duration_days > 0),
    status VARCHAR(20) DEFAULT 'unused' CHECK (status IN ('unused', 'active', 'blocked', 'expired', 'suspended')),
    hwid TEXT, -- Hardware / Device ID bound when user logs in with trading bot
    device_model TEXT,
    device_reset_count INTEGER DEFAULT 0 CHECK (device_reset_count >= 0),
    max_device_resets INTEGER DEFAULT 2 CHECK (max_device_resets >= 0),
    activated_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    last_ping_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    notes TEXT
);

-- Indexes for lightning fast lookup during Trading Bot login and Reseller Bot operations
CREATE INDEX IF NOT EXISTS idx_ishak_licenses_key ON ishak_licenses(license_key);
CREATE INDEX IF NOT EXISTS idx_ishak_licenses_reseller ON ishak_licenses(reseller_id);
CREATE INDEX IF NOT EXISTS idx_ishak_licenses_status ON ishak_licenses(status);
CREATE INDEX IF NOT EXISTS idx_ishak_licenses_hwid ON ishak_licenses(hwid);

-- Enable Row Level Security (RLS)
ALTER TABLE ishak_licenses ENABLE ROW LEVEL SECURITY;

-- Allow Service Role to perform all operations
CREATE POLICY "Service Role Full Access" ON ishak_licenses
    FOR ALL
    USING (auth.role() = 'service_role')
    WITH CHECK (auth.role() = 'service_role');

-- Allow Anonymous/Public to Read Active License verification if key matches
CREATE POLICY "Public License Read Verification" ON ishak_licenses
    FOR SELECT
    USING (status != 'blocked');

COMMENT ON TABLE ishak_licenses IS 'Stores all Ishak AI Trading Bot client licenses created by Resellers and Owner.';
